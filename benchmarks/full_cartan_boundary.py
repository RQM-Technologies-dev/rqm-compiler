"""Full Cartan-coordinate sufficiency diagnostic for 3Q recursive readout.

Fits the exact eliminated boundary relation against the full commuting Cartan
generator basis {II, XX, YY, ZZ} on the relevant 2Q boundary before recursive
elimination. This is a sufficiency diagnostic, not an assumed readout rule.
No Pauli-sum production path; dense matrices are only the small-system judge.
"""
import json,math,random
from pathlib import Path
import numpy as np
from rqm_compiler import Circuit
from rqm_compiler.verification import _apply_gate_to_state
from rqm_compiler.su4_blocks import _operation_matrix

I=np.eye(2,dtype=complex);X=np.array([[0,1],[1,0]],complex);Y=np.array([[0,-1j],[1j,0]],complex);Z=np.array([[1,0],[0,-1]],complex)
ZERO=np.array([[1,0],[0,0]],complex)
B=[np.kron(I,I),np.kron(X,X),np.kron(Y,Y),np.kron(Z,Z)]

def block(a,b):
 c=Circuit(2);c.rxx(0,1,a);c.rzz(0,1,b);c.cx(0,1);U=np.eye(4,dtype=complex)
 for op in c.operations:U=_operation_matrix(op,(0,1))@U
 return U

def cartan_project(A):
 coeff=np.array([np.trace(b.conj().T@A)/4 for b in B],complex)
 recon=sum(c*b for c,b in zip(coeff,B))
 return coeff,recon,float(np.linalg.norm(A-recon))

def dense(a01,b01,a12,b12):
 c=Circuit(3);c.rxx(0,1,a01);c.rzz(0,1,b01);c.cx(0,1);c.rxx(1,2,a12);c.rzz(1,2,b12);c.cx(1,2)
 s=[0j]*8;s[0]=1+0j
 for op in c.operations:s=_apply_gate_to_state(s,op,3)
 return float(sum(abs(x)**2*((-1)**i.bit_count()) for i,x in enumerate(s)))

def candidate(a01,b01,a12,b12):
 U12=block(a12,b12)
 # Exact two-qubit Heisenberg relation generated by leaf observable.
 A12=U12.conj().T@np.kron(Z,I)@U12
 coeff,recon,resid=cartan_project(A12)
 # Use only full Cartan projection, then contract q2 input to q1 boundary.
 C=np.kron(ZERO,I)@recon;x=C.reshape(2,2,2,2);M1=np.einsum("abad->bd",x)
 U01=block(a01,b01)
 A01=U01.conj().T@np.kron(Z@M1,I)@U01
 D=np.kron(ZERO,I)@A01;y=D.reshape(2,2,2,2);M0=np.einsum("abad->bd",y)
 return float(M0[0,0].real),resid,coeff

rng=random.Random(41);rows=[]
for k in range(128):
 a01,b01,a12,b12=[rng.uniform(-math.pi,math.pi) for _ in range(4)]
 val,resid,coeff=candidate(a01,b01,a12,b12);ref=dense(a01,b01,a12,b12)
 rows.append({"case":k,"cartan_residual":resid,"error":abs(val-ref),"value":val,"reference":ref,
 "cartan_coeff_abs":[float(abs(x)) for x in coeff]})
summary={"cases":128,"cartan_closed":sum(r["cartan_residual"]<=1e-9 for r in rows),
"exact_cases":sum(r["error"]<=1e-9 for r in rows),"median_cartan_residual":float(np.median([r["cartan_residual"] for r in rows])),
"max_cartan_residual":max(r["cartan_residual"] for r in rows),"median_error":float(np.median([r["error"] for r in rows])),"max_error":max(r["error"] for r in rows)}
Path("results").mkdir(exist_ok=True);Path("results/full_cartan_boundary.json").write_text(json.dumps({"summary":summary,"rows":rows},indent=2));print(json.dumps(summary))
